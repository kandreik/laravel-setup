<?php
/*
 * Лабораторна робота №2, завдання 2. Вихід із системи.
 */

session_start();

// 1. Прибираємо змінні сесії
session_unset();

// 2. Видаляємо файл сесії на сервері
session_destroy();

// 3. Просимо браузер видалити cookie з ідентифікатором сесії
setcookie(session_name(), "", time() - 3600, "/");

// 4. Повертаємо користувача на головну сторінку
header("Location: index.php");
exit;
